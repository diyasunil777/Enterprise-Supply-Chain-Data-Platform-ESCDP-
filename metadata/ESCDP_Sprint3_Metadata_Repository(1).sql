SELECT sa.asset_id, et.transformation_id, ta.asset_id, ls.rule, ls.purpose
FROM lineage_seed ls
JOIN governance.metadata_asset sa
  ON sa.schema_name=ls.src_schema AND sa.asset_name=ls.src_table AND sa.asset_type='SOURCE_TABLE'
JOIN governance.etl_transformation et ON et.transformation_name=ls.trans_name
JOIN governance.metadata_asset ta
  ON ta.schema_name=ls.tgt_schema AND ta.asset_name=ls.tgt_table
