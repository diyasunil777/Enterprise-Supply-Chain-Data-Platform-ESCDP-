-- ============================================================
-- ESCDP / UC18 - Sprint 3 Metadata Repository
-- PostgreSQL SQL script
--
-- Purpose:
--   Create a metadata repository that documents the source tables,
--   Pentaho transformations, warehouse targets, column mappings,
--   data lineage, Power BI dashboard assets, and data-quality checks.
--
-- Important:
--   This script creates metadata tables in schema governance.
--   It does NOT modify or reload public source data or warehouse facts.
--   Run it in the SAME PostgreSQL database used by ESCDP.
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS governance;

-- 1. Catalog of source, staging, warehouse and analytics assets.
CREATE TABLE IF NOT EXISTS governance.metadata_asset (
    asset_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_name         TEXT NOT NULL,
    schema_name        TEXT NOT NULL,
    asset_type         TEXT NOT NULL CHECK (
        asset_type IN ('SOURCE_TABLE','WAREHOUSE_DIMENSION','WAREHOUSE_FACT',
                       'TRANSFORMATION','POWER_BI_PAGE','POWER_BI_VISUAL')
    ),
    layer_name         TEXT NOT NULL,
    business_description TEXT,
    owner_or_team      TEXT DEFAULT 'ESCDP Data Engineering',
    status             TEXT NOT NULL DEFAULT 'DOCUMENTED'
                       CHECK (status IN ('DOCUMENTED','CONFIGURED','VALIDATED','NEEDS_REVIEW')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (schema_name, asset_name, asset_type)
);

-- 2. Transformation/job catalog. One row per Pentaho .ktr transformation.
CREATE TABLE IF NOT EXISTS governance.etl_transformation (
    transformation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transformation_name TEXT NOT NULL UNIQUE,
    file_name           TEXT NOT NULL,
    tool_name           TEXT NOT NULL DEFAULT 'Pentaho Data Integration',
    input_pattern       TEXT NOT NULL DEFAULT 'Table Input -> Select Values -> Table Output',
    target_schema       TEXT,
    target_table        TEXT,
    transformation_logic TEXT,
    execution_status    TEXT NOT NULL DEFAULT 'CONFIGURED'
                        CHECK (execution_status IN ('CONFIGURED','SUCCEEDED','FAILED','NEEDS_REVIEW')),
    last_run_at         TIMESTAMPTZ,
    last_run_rows       BIGINT,
    notes               TEXT
);

-- 3. Source-to-target lineage at table level.
CREATE TABLE IF NOT EXISTS governance.data_lineage (
    lineage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_asset_id BIGINT NOT NULL REFERENCES governance.metadata_asset(asset_id),
    transformation_id BIGINT REFERENCES governance.etl_transformation(transformation_id),
    target_asset_id BIGINT NOT NULL REFERENCES governance.metadata_asset(asset_id),
    lineage_type TEXT NOT NULL DEFAULT 'ETL_LOAD'
                 CHECK (lineage_type IN ('ETL_LOAD','DIMENSION_LOOKUP','REPORT_CONSUMPTION')),
    transformation_rule TEXT,
    business_purpose TEXT,
    validation_status TEXT NOT NULL DEFAULT 'NEEDS_REVIEW'
                      CHECK (validation_status IN ('NEEDS_REVIEW','PASSED','FAILED','NOT_TESTED')),
    UNIQUE (source_asset_id, transformation_id, target_asset_id, lineage_type)
);

-- 4. Column-level source-to-target mapping.
CREATE TABLE IF NOT EXISTS governance.column_mapping (
    mapping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transformation_id BIGINT REFERENCES governance.etl_transformation(transformation_id),
    source_asset_id BIGINT REFERENCES governance.metadata_asset(asset_id),
    source_column TEXT NOT NULL,
    target_asset_id BIGINT REFERENCES governance.metadata_asset(asset_id),
    target_column TEXT NOT NULL,
    transformation_rule TEXT,
    data_type_note TEXT,
    business_definition TEXT,
    validation_status TEXT NOT NULL DEFAULT 'NEEDS_REVIEW'
                      CHECK (validation_status IN ('NEEDS_REVIEW','PASSED','FAILED','NOT_TESTED'))
);

-- 5. Data dictionary for important fields.
CREATE TABLE IF NOT EXISTS governance.column_dictionary (
    dictionary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL REFERENCES governance.metadata_asset(asset_id),
    column_name TEXT NOT NULL,
    business_name TEXT,
    data_classification TEXT NOT NULL DEFAULT 'INTERNAL'
                       CHECK (data_classification IN ('PUBLIC','INTERNAL','CONFIDENTIAL','RESTRICTED')),
    business_definition TEXT,
    source_or_derivation TEXT,
    nullable_expectation TEXT,
    quality_rule TEXT,
    UNIQUE (asset_id, column_name)
);

-- 6. Power BI pages and visual/measure inventory.
CREATE TABLE IF NOT EXISTS governance.analytics_asset (
    analytics_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_name TEXT NOT NULL,
    visual_name TEXT NOT NULL,
    visual_type TEXT,
    metric_or_fields TEXT,
    expected_warehouse_source TEXT,
    business_question TEXT,
    validation_note TEXT,
    status TEXT NOT NULL DEFAULT 'NEEDS_REVIEW'
           CHECK (status IN ('DOCUMENTED','VALIDATED','NEEDS_REVIEW')),
    UNIQUE (page_name, visual_name)
);

-- 7. Data quality rule catalog and execution results.
CREATE TABLE IF NOT EXISTS governance.data_quality_rule (
    rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name TEXT NOT NULL UNIQUE,
    asset_schema TEXT,
    asset_table TEXT,
    rule_description TEXT NOT NULL,
    sql_check TEXT,
    expected_result TEXT,
    severity TEXT NOT NULL DEFAULT 'MEDIUM'
            CHECK (severity IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS governance.data_quality_result (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL REFERENCES governance.data_quality_rule(rule_id),
    checked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    run_reference TEXT,
    observed_value TEXT,
    passed BOOLEAN,
    issue_details TEXT
);

